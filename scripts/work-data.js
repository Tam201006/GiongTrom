function renderDoanSection(data) {
  const container = document.querySelector('#doan-container > .content-container');
  if (!container) return;

  const html = data.map(module => `
    <div class="part" id="${module.moduleId}">
      <div class="title">${module.mainTitle}</div>
      <div class="descript">
        ${module.mainDescript.map(p => `<p>${p}</p>`).join('')}
      </div>
      
      ${module.sections.map(sec => `
        <div class="doan">
          <div class="title">${sec.title}</div>
          <div class="content">
            ${sec.paragraphs.map(p => `<p>${p}</p>`).join('')}
            ${sec.quote ? `<p class="study-text">${sec.quote}</p>` : ''}
          </div>
        </div>
      `).join('')}
    </div>
  `).join('');

  container.innerHTML = html;
}
