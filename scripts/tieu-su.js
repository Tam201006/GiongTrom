function renderTieuSu() {
  const container = document.querySelector('#tieu-su .body');
  if (!container) return;

  // Tạo chuỗi HTML bằng map và join
  const htmlContent = contentData.map(item => `
        <div class="part">
          <div class="title">${item.title}</div>
          <div class="text">
            ${item.p1 ? `<p>${item.p1}</p>` : ''}
            ${item.p2 ? `<p>${item.p2}</p>` : ''}
            ${item.p3 ? `<p>${item.p3}</p>` : ''}
            ${item.p4 ? `<p>${item.p4}</p>` : ''}
            ${item.p5 ? `<p>${item.p5}</p>` : ''}
          </div>
        </div>
  `).join('');

  // Gán vào container
  container.innerHTML = htmlContent;
}

// Gọi hàm render (Ví dụ render vào thẻ có id="app")
document.addEventListener('DOMContentLoaded', () => {
  renderTieuSu();
});
